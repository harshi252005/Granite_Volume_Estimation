// ── Hook ─────────────────────────────────────────────────────────────────────
export function usePermission(user) {
  const role = user?.role || 'operator';
  const allowed = PERMISSIONS[role] || [];

  return {
    can: (feature) => allowed.includes(feature),
    role,
    isAdmin: role === 'admin',
    isDMGO: role === 'dmgo',
    isOperator: role === 'operator',
    isWeighbridge: role === 'weighbridge',
    isCitizen: role === 'citizen',
    isEnforcement: role === 'enforcement',
  };
}


